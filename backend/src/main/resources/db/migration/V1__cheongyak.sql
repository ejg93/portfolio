-- 청약 공고·주택형·수집 이력. H2(PostgreSQL 모드)와 Postgres 양쪽에서 도는 문법만 쓴다
CREATE TABLE cheongyak_notice (
  house_manage_no   VARCHAR(20)  NOT NULL,
  pblanc_no         VARCHAR(20)  NOT NULL,
  kind              VARCHAR(10)  NOT NULL,  -- APT | URBTY | REMNDR | PBLPVT | OPT
  house_secd        VARCHAR(4),
  house_secd_nm     VARCHAR(60),
  house_dtl_secd    VARCHAR(4),
  house_dtl_secd_nm VARCHAR(60),
  rent_secd         VARCHAR(2),
  house_nm          VARCHAR(200) NOT NULL,
  area_code         VARCHAR(10),
  area_nm           VARCHAR(30),
  address           VARCHAR(300),
  tot_suply_hshldco INTEGER,
  rcrit_pblanc_de   DATE,
  rcept_bgnde       DATE,  rcept_endde       DATE,
  spsply_bgnde      DATE,  spsply_endde      DATE,
  rnk1_crsp_bgnde   DATE,  rnk1_crsp_endde   DATE,
  rnk1_gg_bgnde     DATE,  rnk1_gg_endde     DATE,
  rnk1_etc_bgnde    DATE,  rnk1_etc_endde    DATE,
  rnk2_crsp_bgnde   DATE,  rnk2_crsp_endde   DATE,
  rnk2_gg_bgnde     DATE,  rnk2_gg_endde     DATE,
  rnk2_etc_bgnde    DATE,  rnk2_etc_endde    DATE,
  przwner_de        DATE,
  cntrct_bgnde      DATE,  cntrct_endde      DATE,
  mvn_prearnge_ym   VARCHAR(10),
  speclt_rdn_at     VARCHAR(1),
  mdat_trget_at     VARCHAR(1),
  parcprc_uls_at    VARCHAR(1),
  imprmn_bsns_at    VARCHAR(1),
  public_house_at   VARCHAR(1),
  lrscl_bldlnd_at   VARCHAR(1),
  npln_pub_house_at VARCHAR(1),
  bsns_mby_nm       VARCHAR(200),
  cnstrct_entrps_nm VARCHAR(200),
  hmpg_adres        VARCHAR(500),
  pblanc_url        VARCHAR(500),
  -- 공고문 PDF 에서 뽑은 값. doc_status: OK | NO_LINK | NO_PDF | PARSE_ERR | HTTP_<코드>, 아직 안 받았으면 null
  doc_status          VARCHAR(20),
  doc_remndr_area     VARCHAR(10),   -- 서울|인천|경기|수도권|전국 (무순위 자격)
  doc_remndr_homeless VARCHAR(1),    -- Y|N
  doc_rewin_years     INTEGER,       -- 0 = 없음
  doc_regulation      VARCHAR(10),   -- 투기과열|청약과열|비규제
  doc_crsp_city       VARCHAR(20),   -- 해당지역이 시 단위면 시군 이름(「시」「군」 뗌)
  doc_crsp_months     INTEGER,
  doc_res_pri_area    VARCHAR(20),
  doc_res_pri_months  INTEGER,
  doc_point_le60      INTEGER,
  doc_point_le85      INTEGER,
  doc_point_gt85      INTEGER,
  doc_fetched_at      TIMESTAMP,
  raw_json          TEXT NOT NULL,
  first_seen_at     TIMESTAMP NOT NULL,
  updated_at        TIMESTAMP NOT NULL,
  PRIMARY KEY (house_manage_no, pblanc_no)
);
CREATE INDEX ix_notice_pblanc_de ON cheongyak_notice (rcrit_pblanc_de);
CREATE INDEX ix_notice_area ON cheongyak_notice (area_nm);

CREATE TABLE cheongyak_house_type (
  house_manage_no    VARCHAR(20)  NOT NULL,
  pblanc_no          VARCHAR(20)  NOT NULL,
  model_no           VARCHAR(10)  NOT NULL,
  house_ty           VARCHAR(60),
  exclusive_area     NUMERIC(8,4),
  supply_area        NUMERIC(8,4),
  suply_hshldco      INTEGER,
  spsply_hshldco     INTEGER,
  mnych_hshldco      INTEGER, nwwds_hshldco INTEGER, lfe_frst_hshldco INTEGER,
  old_parnts_hshldco INTEGER, instt_hshldco INTEGER, etc_hshldco INTEGER,
  transr_hshldco     INTEGER, ygmn_hshldco INTEGER, nwbb_hshldco INTEGER,
  top_amount         BIGINT,
  raw_json           TEXT NOT NULL,
  PRIMARY KEY (house_manage_no, pblanc_no, model_no),
  FOREIGN KEY (house_manage_no, pblanc_no) REFERENCES cheongyak_notice (house_manage_no, pblanc_no) ON DELETE CASCADE
);

CREATE TABLE cheongyak_collect_run (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  started_at    TIMESTAMP NOT NULL,
  finished_at   TIMESTAMP,
  status        VARCHAR(10) NOT NULL,  -- RUNNING | OK | FAIL
  trigger_src   VARCHAR(20) NOT NULL,  -- cron | manual
  since_date    DATE NOT NULL,
  fetched       INTEGER NOT NULL DEFAULT 0,
  inserted      INTEGER NOT NULL DEFAULT 0,
  updated       INTEGER NOT NULL DEFAULT 0,
  remndr_count  INTEGER NOT NULL DEFAULT 0,
  api_calls     INTEGER NOT NULL DEFAULT 0,
  doc_fetched   INTEGER NOT NULL DEFAULT 0,
  doc_ok        INTEGER NOT NULL DEFAULT 0,
  doc_pending   INTEGER NOT NULL DEFAULT 0,
  error_message VARCHAR(1000)
);
