-- 청약 경쟁률. 행 = 주택형 × 거주 구분 × 순위(무순위는 0)
CREATE TABLE cheongyak_cmpet (
  house_manage_no VARCHAR(20) NOT NULL,
  pblanc_no       VARCHAR(20) NOT NULL,
  house_ty        VARCHAR(60) NOT NULL,
  reside_nm       VARCHAR(20) NOT NULL,
  rank_code       INTEGER     NOT NULL,
  suply_hshldco   INTEGER,
  req_cnt         INTEGER,
  cmpet_rate      NUMERIC(10,2),          -- 숫자가 아니면 null, 원래 표기는 cmpet_text
  cmpet_text      VARCHAR(20),
  raw_json        TEXT NOT NULL,
  PRIMARY KEY (house_manage_no, pblanc_no, house_ty, reside_nm, rank_code),
  FOREIGN KEY (house_manage_no, pblanc_no) REFERENCES cheongyak_notice (house_manage_no, pblanc_no) ON DELETE CASCADE
);

-- APT 당첨가점. 행 = 주택형 × 거주 구분
CREATE TABLE cheongyak_score (
  house_manage_no VARCHAR(20) NOT NULL,
  pblanc_no       VARCHAR(20) NOT NULL,
  house_ty        VARCHAR(60) NOT NULL,
  reside_nm       VARCHAR(20) NOT NULL,
  min_score       INTEGER,
  max_score       INTEGER,
  avg_score       NUMERIC(6,2),
  raw_json        TEXT NOT NULL,
  PRIMARY KEY (house_manage_no, pblanc_no, house_ty, reside_nm),
  FOREIGN KEY (house_manage_no, pblanc_no) REFERENCES cheongyak_notice (house_manage_no, pblanc_no) ON DELETE CASCADE
);

-- 실거래 월 단위 캐시. 한 (시군구, 계약월) 을 받으면 그 달 거래를 통째로 바꾼다(실거래 API 에 고유 ID 가 없다)
CREATE TABLE cheongyak_rtms_month (
  lawd_cd     VARCHAR(5) NOT NULL,
  deal_ymd    VARCHAR(6) NOT NULL,
  fetched_at  TIMESTAMP  NOT NULL,
  trade_count INTEGER    NOT NULL,
  api_calls   INTEGER    NOT NULL,
  PRIMARY KEY (lawd_cd, deal_ymd)
);

CREATE TABLE cheongyak_rtms_trade (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lawd_cd      VARCHAR(5)  NOT NULL,
  deal_ymd     VARCHAR(6)  NOT NULL,
  umd_nm       VARCHAR(30),
  apt_nm       VARCHAR(100),
  jibun        VARCHAR(30),
  exclu_use_ar NUMERIC(8,4),
  deal_amount  BIGINT,                   -- 만원
  floor_no     INTEGER,
  build_year   INTEGER,
  deal_day     INTEGER,
  canceled     VARCHAR(1),               -- 해제 신고면 Y
  dealing_gbn  VARCHAR(10),
  raw_json     TEXT NOT NULL
);
CREATE INDEX ix_rtms_trade_month ON cheongyak_rtms_trade (lawd_cd, deal_ymd);
CREATE INDEX ix_rtms_trade_umd ON cheongyak_rtms_trade (lawd_cd, umd_nm, build_year);

